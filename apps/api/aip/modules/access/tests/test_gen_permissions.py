"""``tools/gen_permissions.py`` (ACCESS-01 step 3): deterministic output and the drift check."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[6]
SCRIPT = ROOT / "tools" / "gen_permissions.py"
OUTPUT = ROOT / "packages" / "contracts" / "src" / "permissions.generated.ts"


def run(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(SCRIPT), *args], capture_output=True, text=True, check=False
    )


def test_regenerating_twice_is_byte_identical() -> None:
    first = run()
    assert first.returncode == 0, first.stderr
    content = OUTPUT.read_bytes()
    second = run()
    assert second.returncode == 0, second.stderr
    assert OUTPUT.read_bytes() == content


def test_committed_file_matches_the_manifests() -> None:
    result = run("--check")
    assert result.returncode == 0, result.stderr


def test_output_lists_codes_sorted_with_privileged_flags() -> None:
    text = OUTPUT.read_text(encoding="utf-8")
    assert text.startswith("// @generated by tools/gen_permissions.py")
    assert '  | "access.role.manage"' in text
    assert '"access.role.manage": { module: "access", privileged: true },' in text
    codes = [line.split('"')[1] for line in text.splitlines() if line.startswith('  | "')]
    assert codes == sorted(codes)
