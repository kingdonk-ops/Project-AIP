#!/usr/bin/env python3
"""Write ``packages/contracts/src/permissions.generated.ts`` from the module manifests (ACCESS-01).

    uv run python tools/gen_permissions.py           # regenerate
    uv run python tools/gen_permissions.py --check   # exit 1 when the committed file is stale

The catalogue is built exactly as ``create_app()`` builds it (``aip.platform.access``), from every
``apps/api/aip/modules/*/manifest.toml``; nothing is imported from the modules and no database is
needed. The output is sorted by code, so regenerating is deterministic. CI runs ``--check``.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULES_DIR = ROOT / "apps" / "api" / "aip" / "modules"
OUTPUT = ROOT / "packages" / "contracts" / "src" / "permissions.generated.ts"

sys.path.insert(0, str(ROOT / "apps" / "api"))

from aip.platform.access.catalogue import build_catalogue, load_manifests  # noqa: E402

HEADER = "// @generated by tools/gen_permissions.py (ACCESS-01) — do not edit"


def render(modules_dir: Path = MODULES_DIR) -> str:
    catalogue = build_catalogue(load_manifests(modules_dir))
    lines = [
        HEADER,
        "// Permission codes declared by the API module manifests. Regenerate with:",
        "//   uv run python tools/gen_permissions.py",
        "",
        "export type PermissionCode =",
    ]
    codes = list(catalogue)
    if codes:
        lines += [f"  | {json.dumps(code)}" for code in codes]
        lines[-1] += ";"
    else:
        lines[-1] += " never;"
    lines += [
        "",
        "export const PERMISSIONS = {",
        *(
            f"  {json.dumps(p.code)}: {{ module: {json.dumps(p.module_id)}, "
            f"privileged: {'true' if p.privileged else 'false'} }},"
            for p in catalogue.values()
        ),
        "} as const satisfies Record<PermissionCode, { module: string; privileged: boolean }>;",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    content = render()
    if argv == ["--check"]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else None
        if current != content:
            print(
                f"{OUTPUT.relative_to(ROOT)} is out of date; "
                "run `uv run python tools/gen_permissions.py` and commit it",
                file=sys.stderr,
            )
            return 1
        print(f"ok: {OUTPUT.relative_to(ROOT)} matches the manifests")
        return 0
    if argv:
        print(__doc__, file=sys.stderr)
        return 2
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
